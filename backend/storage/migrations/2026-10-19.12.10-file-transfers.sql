CREATE TABLE IF NOT EXISTS `featherpanel_file_transfers` (
	`id` INT (11) NOT NULL AUTO_INCREMENT,
	`uuid` CHAR(36) NOT NULL,
	`user_id` INT (11) NOT NULL,
	`source_server_id` INT (11) NOT NULL,
	`target_server_id` INT (11) NOT NULL,
	`mode` ENUM ('copy', 'move') NOT NULL DEFAULT 'copy',
	`source_root` VARCHAR(1024) NOT NULL DEFAULT '/',
	`files` TEXT NOT NULL,
	`destination` VARCHAR(1024) NOT NULL DEFAULT '/',
	`status` ENUM ('pending', 'running', 'completed', 'failed') NOT NULL DEFAULT 'pending',
	`progress` TINYINT UNSIGNED NOT NULL DEFAULT 0,
	`stage` VARCHAR(32) NOT NULL DEFAULT 'queued',
	`method` VARCHAR(16) DEFAULT NULL,
	`error` TEXT DEFAULT NULL,
	`created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	`updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
	`finished_at` DATETIME DEFAULT NULL,
	PRIMARY KEY (`id`),
	UNIQUE KEY `uniq_file_transfer_uuid` (`uuid`),
	KEY `idx_file_transfer_user` (`user_id`, `created_at`),
	CONSTRAINT `fk_file_transfer_user` FOREIGN KEY (`user_id`) REFERENCES `featherpanel_users` (`id`) ON DELETE CASCADE,
	CONSTRAINT `fk_file_transfer_source` FOREIGN KEY (`source_server_id`) REFERENCES `featherpanel_servers` (`id`) ON DELETE CASCADE,
	CONSTRAINT `fk_file_transfer_target` FOREIGN KEY (`target_server_id`) REFERENCES `featherpanel_servers` (`id`) ON DELETE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_general_ci;
